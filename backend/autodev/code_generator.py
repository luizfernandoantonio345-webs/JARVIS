"""
code_generator — FASE 10 AutoDev Engine, Component 2

Generates source code file-by-file using the LLM Service, maintaining
project-wide coherence by injecting accumulated context into each call.

Responsibilities
----------------
  1. Receive a ``ProjectBlueprint`` from the Scaffolder.
  2. For each ``FileSpec``, call the LLM with:
       - A system prompt describing the full project stack and goal.
       - The file's purpose and language.
       - Context from already-generated files (capped at 3000 chars).
  3. Write the generated code to the workspace.
  4. Return a list of ``GeneratedFile`` records for the Validator.

Role in the system
------------------
Second stage in the AutoDev pipeline:
  scaffolder → **code_generator** → validator → auto_fixer → done

Usage example
-------------
>>> from backend.autodev.code_generator import CodeGenerator
>>> gen = CodeGenerator(job_id="abc123", workspace="/workspace/jobs/abc123")
>>> files = await gen.generate(blueprint)
>>> for gf in files:
...     print(gf.path, "—", len(gf.code), "chars")
"""

from __future__ import annotations

import asyncio
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import structlog

from backend.services.llm_service import call_llm
from backend.autodev.scaffolder import FileSpec, ProjectBlueprint
from backend.autodev.context_tracker import ProjectContext

log = structlog.get_logger(__name__)

# ── Models ─────────────────────────────────────────────────────────────────────

@dataclass
class GeneratedFile:
    path: str
    language: str
    code: str
    purpose: str

    @property
    def workspace_path(self) -> Path:
        return Path(self.path)


# ── Boilerplate templates ──────────────────────────────────────────────────────
# For files that are pure config — generate them directly without an LLM call.

_BOILERPLATE: dict[str, str] = {
    "requirements.txt": "# Add your dependencies here\n",
    "package.json": '{\n  "name": "project",\n  "version": "1.0.0"\n}\n',
    ".gitignore": "__pycache__/\n*.pyc\n.env\nnode_modules/\n",
    "README.md": "# Project\n\nAuto-generated by JARVIS AutoDev Engine.\n",
}

_SKIP_GENERATE = frozenset({"requirements.txt", "package.json", ".gitignore"})

# ── Prompts ────────────────────────────────────────────────────────────────────

_CODEGEN_SYSTEM = """\
You are an expert software engineer. Generate complete, production-quality code.

Rules:
- Output ONLY the raw source code — no markdown fences, no explanations.
- The code must be complete and immediately runnable.
- Follow the language's idiomatic conventions.
- Include all required imports.
- Add concise docstrings for public functions/classes.
"""


# ── Generator ──────────────────────────────────────────────────────────────────

class CodeGenerator:
    """
    Generates code for every file in a ProjectBlueprint.

    Parameters
    ----------
    job_id:    AutoDev job identifier.
    workspace: Absolute path to the isolated job directory.
    """

    def __init__(self, job_id: str, workspace: str | Path) -> None:
        self.job_id = job_id
        self.workspace = Path(workspace)
        self._ctx: ProjectContext | None = None  # set by generate()

    async def generate(
        self,
        blueprint: ProjectBlueprint,
        resume_context: ProjectContext | None = None,
    ) -> list[GeneratedFile]:
        """
        Generate code for every file in *blueprint*, write to disk, return results.

        Coherence is maintained by a ProjectContext that tracks all generated
        file interfaces/exports and is persisted to context.json after each file.

        Parameters
        ----------
        blueprint:      Scaffolder blueprint to generate.
        resume_context: Pre-loaded ProjectContext for job resume; if supplied,
                        files that already exist on disk are skipped.

        Usage example
        -------------
        >>> files = await generator.generate(blueprint)
        >>> for f in files:
        ...     print(f.path, len(f.code))
        """
        log.info("code_generator.start", job_id=self.job_id, files=len(blueprint.files))

        # Initialise or reuse context
        self._ctx = resume_context or ProjectContext(
            job_id=self.job_id,
            workspace=self.workspace,
            goal=blueprint.goal,
            stack=blueprint.stack,
        )

        generated: list[GeneratedFile] = []
        already_done = set(self._ctx.generated_paths)

        for spec in blueprint.files:
            full_path = self.workspace / spec.path

            # Resume: if file was already generated in a previous run, reload it
            if spec.path in already_done and full_path.exists():
                existing_code = full_path.read_text(encoding="utf-8")
                gf = GeneratedFile(
                    path=spec.path,
                    language=spec.language,
                    code=existing_code,
                    purpose=spec.purpose,
                )
                generated.append(gf)
                log.debug("code_generator.resumed", path=spec.path)
                continue

            gf = await self._generate_file(spec, blueprint)
            generated.append(gf)

            # Update accumulating context and persist
            self._ctx.add(gf)
            self._ctx.save()

        log.info("code_generator.done", job_id=self.job_id, files=len(generated))
        return generated

    # ── Internals ──────────────────────────────────────────────────────────────

    async def _generate_file(
        self,
        spec: FileSpec,
        blueprint: ProjectBlueprint,
    ) -> GeneratedFile:
        filename = Path(spec.path).name

        # Use existing pre-populated content or boilerplate for manifest files
        if filename in _SKIP_GENERATE and spec.content.strip():
            code = spec.content
            log.debug("code_generator.boilerplate", path=spec.path)
        elif filename in _BOILERPLATE and not spec.content.strip():
            code = _BOILERPLATE[filename]
        else:
            code = await self._call_llm(spec, blueprint)

        # Write to disk
        full_path = self.workspace / spec.path
        full_path.parent.mkdir(parents=True, exist_ok=True)
        full_path.write_text(code, encoding="utf-8")
        log.debug("code_generator.written", path=spec.path, chars=len(code))

        return GeneratedFile(
            path=spec.path,
            language=spec.language,
            code=code,
            purpose=spec.purpose,
        )

    async def _call_llm(
        self,
        spec: FileSpec,
        blueprint: ProjectBlueprint,
    ) -> str:
        # Build context from ProjectContext (includes interface summaries)
        ctx_text = (
            self._ctx.render_for_prompt(max_chars=3000)
            if self._ctx
            else f"Project: {blueprint.goal}\nStack: {blueprint.stack}"
        )
        prompt = (
            f"Project context:\n{ctx_text}\n\n"
            f"Generate the file: {spec.path}\n"
            f"Language: {spec.language}\n"
            f"Purpose: {spec.purpose}\n\n"
            "Output raw source code only:"
        )
        raw = await asyncio.get_event_loop().run_in_executor(
            None,
            lambda: call_llm(
                [
                    {"role": "system", "content": _CODEGEN_SYSTEM},
                    {"role": "user",   "content": prompt},
                ],
                force_api=False,
            ),
        )
        code = raw or f"# TODO: implement {spec.path}\n"
        # Strip accidental markdown fences
        code = re.sub(r"^```[a-z]*\n?", "", code, flags=re.MULTILINE)
        code = re.sub(r"\n?```$", "", code, flags=re.MULTILINE)
        return code.strip() + "\n"
