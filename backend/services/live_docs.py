"""
live_docs — Documentação Viva Automática  (FASE 13B)

Hooks that run automatically after AutoDev jobs and agent executions:
  • generate_project_readme(job_dir)   — README.md do projeto criado
  • update_changelog(job_id, summary)  — CHANGELOG.md global
  • generate_docstrings(file_path)     — Docstrings em código gerado
  • log_to_wiki(entry)                 — Wiki interna do Jarvis
  • search_wiki(query)                 — Busca semântica na wiki
"""

from __future__ import annotations

import json
import logging
import re
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from config import get_config

log = logging.getLogger(__name__)

_WIKI_DIR      = Path(__file__).parent.parent / "reports" / "wiki"
_CHANGELOG_FILE = Path(__file__).parent.parent / "reports" / "CHANGELOG.md"
_WIKI_INDEX     = _WIKI_DIR / "index.jsonl"

_WIKI_DIR.mkdir(parents=True, exist_ok=True)
_CHANGELOG_FILE.parent.mkdir(parents=True, exist_ok=True)


# ── README generation ─────────────────────────────────────────────────────────

async def generate_project_readme(job_dir: Path | str) -> str:
    """
    Generate a README.md inside the job directory based on its state.json
    and the files it contains.  Returns the generated markdown.
    """
    job_dir = Path(job_dir)
    state_file = job_dir / "state.json"
    if not state_file.exists():
        log.warning("live_docs: no state.json in %s", job_dir)
        return ""

    try:
        state = json.loads(state_file.read_text(encoding="utf-8"))
    except Exception as exc:
        log.warning("live_docs: unreadable state.json: %s", exc)
        return ""

    goal   = state.get("goal", "Unknown project")
    job_id = state.get("job_id", job_dir.name)
    created = state.get("created_at", "")[:10]
    status = state.get("status", "unknown")

    # Collect generated files
    src_files = [f.relative_to(job_dir) for f in job_dir.rglob("*")
                 if f.is_file() and f.name not in {"state.json", "README.md"}]
    file_list = "\n".join(f"- `{f}`" for f in sorted(src_files)[:30])

    readme = f"""# {goal}

> Auto-generated by JARVIS on {created}

## Overview
Job `{job_id}` — Status: **{status}**

**Goal:** {goal}

## Files
{file_list or "_No files recorded._"}

## How to run
```bash
# Inspect the project files in this directory
ls {job_dir}
```

---
*This README was automatically generated by JARVIS live_docs.*
"""

    readme_path = job_dir / "README.md"
    readme_path.write_text(readme, encoding="utf-8")
    log.info("live_docs: README.md generated at %s", readme_path)
    return readme


# ── CHANGELOG update ──────────────────────────────────────────────────────────

def update_changelog(job_id: str, summary: str, agent: str = "AutoDev") -> None:
    """
    Prepend an entry to the global CHANGELOG.md.
    Called after every AutoDev job or significant agent action.
    """
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    entry = f"## [{now}] `{agent}` — job `{job_id}`\n\n{summary.strip()}\n\n---\n\n"

    try:
        existing = _CHANGELOG_FILE.read_text(encoding="utf-8") if _CHANGELOG_FILE.exists() else ""
        header = "# JARVIS CHANGELOG\n\nAuto-generated log of all agent actions.\n\n---\n\n"
        if not existing:
            _CHANGELOG_FILE.write_text(header + entry, encoding="utf-8")
        else:
            # Insert after header line
            insert_after = "---\n\n"
            idx = existing.find(insert_after)
            if idx >= 0:
                new_content = existing[: idx + len(insert_after)] + entry + existing[idx + len(insert_after):]
            else:
                new_content = existing + entry
            _CHANGELOG_FILE.write_text(new_content, encoding="utf-8")
        log.info("live_docs: CHANGELOG updated for job %s", job_id)
    except Exception as exc:
        log.warning("live_docs: CHANGELOG update failed: %s", exc)


# ── Docstring injection ───────────────────────────────────────────────────────

async def generate_docstrings(file_path: Path | str) -> int:
    """
    Add Google-style docstrings to Python functions/classes missing them.
    Uses the local LLM (fast model).  Returns count of docstrings added.
    """
    file_path = Path(file_path)
    if not file_path.exists() or file_path.suffix != ".py":
        return 0

    source = file_path.read_text(encoding="utf-8")
    # Find functions/classes without docstrings
    pattern = re.compile(
        r'(def [^\n]+:\n(?:\s+"""|\s+\'\'\')?)',
        re.MULTILINE,
    )
    missing = [m.group() for m in pattern.finditer(source)
               if '"""' not in m.group() and "'''" not in m.group()]
    if not missing:
        return 0

    prompt = (
        f"Add Google-style docstrings to all functions and classes missing them "
        f"in this Python file. Return ONLY the complete modified file content.\n\n"
        f"```python\n{source[:4000]}\n```"
    )

    try:
        from services.llm_service import call_llm
        result = call_llm(
            messages=[{"role": "user", "content": prompt}],
            force_local=True,
        )
        # Extract code block if wrapped
        code_match = re.search(r"```python\n(.*?)```", result, re.DOTALL)
        new_source = code_match.group(1) if code_match else result
        if new_source and len(new_source) > 100:
            file_path.write_text(new_source, encoding="utf-8")
            log.info("live_docs: docstrings added to %s", file_path)
            return len(missing)
    except Exception as exc:
        log.warning("live_docs: docstring gen failed for %s: %s", file_path, exc)
    return 0


# ── Internal Wiki ─────────────────────────────────────────────────────────────

def log_to_wiki(entry: dict[str, Any]) -> None:
    """
    Append an entry to the JSONL wiki index.
    entry should have: type, title, description, tags, job_id (optional)
    """
    record = {
        "ts": datetime.now(timezone.utc).isoformat(),
        "type": entry.get("type", "general"),
        "title": entry.get("title", ""),
        "description": entry.get("description", ""),
        "tags": entry.get("tags", []),
        "job_id": entry.get("job_id", ""),
        "agent": entry.get("agent", ""),
    }
    try:
        with _WIKI_INDEX.open("a", encoding="utf-8") as f:
            f.write(json.dumps(record, ensure_ascii=False) + "\n")
        log.debug("live_docs: wiki entry logged: %s", record["title"])
    except Exception as exc:
        log.warning("live_docs: wiki log failed: %s", exc)


def search_wiki(query: str, max_results: int = 5) -> list[dict]:
    """
    Simple keyword-based wiki search (semantic search available if ChromaDB loaded).
    Returns list of matching wiki entries.
    """
    if not _WIKI_INDEX.exists():
        return []

    query_lower = query.lower()
    results: list[tuple[int, dict]] = []

    try:
        with _WIKI_INDEX.open(encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    rec = json.loads(line)
                except Exception:
                    continue
                # Score by keyword overlap
                text = f"{rec.get('title','')} {rec.get('description','')} {' '.join(rec.get('tags',[]))}".lower()
                score = sum(1 for word in query_lower.split() if word in text)
                if score > 0:
                    results.append((score, rec))
    except Exception as exc:
        log.warning("live_docs: wiki search failed: %s", exc)
        return []

    results.sort(key=lambda x: x[0], reverse=True)
    return [r for _, r in results[:max_results]]


def get_wiki_stats() -> dict:
    """Return stats about the wiki."""
    if not _WIKI_INDEX.exists():
        return {"total_entries": 0, "types": {}}
    try:
        entries = [json.loads(l) for l in _WIKI_INDEX.read_text(encoding="utf-8").splitlines() if l.strip()]
        types: dict[str, int] = {}
        for e in entries:
            t = e.get("type", "general")
            types[t] = types.get(t, 0) + 1
        return {"total_entries": len(entries), "types": types}
    except Exception:
        return {"total_entries": 0, "types": {}}
