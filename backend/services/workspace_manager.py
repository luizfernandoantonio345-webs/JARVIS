# ── Result types ───────────────────────────────────────────────────────────────

@dataclass
class ScaffoldResult:
    project_name: str
    project_path: str
    template: str
    files_created: list[str]
    success: bool
    error: str | None = None

    def to_text(self) -> str:
        if not self.success:
            return f"❌ Scaffold failed: {self.error}"
        lines = [
            f"✅ Project '{self.project_name}' scaffolded at `{self.project_path}`",
            f"Template: {self.template}",
            f"Files created ({len(self.files_created)}):",
        ]
        for f in self.files_created:
            lines.append(f"  • {f}")
        return "\n".join(lines)


@dataclass
class ProjectMeta:
    path: str
    name: str
    type: str        # python | node | unknown
    template: str | None
    entry_point: str | None
    has_deps: bool
    run_command: str


@dataclass
class RunResult:
    project_path: str
    command: str
    exit_code: int | None
    stdout: str
    stderr: str
    duration_s: float
    success: bool
    errors: list[str] = field(default_factory=list)

    def to_text(self) -> str:
        icon = "✅" if self.success else "❌"
        lines = [
            f"{icon} Run: `{self.command}` ({self.duration_s:.1f}s, exit={self.exit_code})",
        ]
        if self.stdout:
            lines.append(f"```\n{self.stdout[:3000]}\n```")
        if self.stderr and not self.success:
            lines.append(f"**Stderr:**\n```\n{self.stderr[:1000]}\n```")
        if self.errors:
            lines.append(f"**Errors detected:** {', '.join(self.errors)}")
        return "\n".join(lines)


# ── WorkspaceManager ───────────────────────────────────────────────────────────

class WorkspaceManager:
    """
    Full project lifecycle manager.

    All paths are validated to be inside WORKSPACE_DIR.
    """

    # ── Scaffolding ────────────────────────────────────────────────────────────

    def scaffold(
        self,
        project_name: str,
        template: ProjectTemplate = "script",
        base_dir: str | None = None,
    ) -> ScaffoldResult:
        """
        Create a new project from a template.

        Args:
            project_name: Human-readable name (spaces → dashes).
            template:     One of the supported template keys.
            base_dir:     Parent directory inside workspace (default: workspace root).

        Returns:
            ScaffoldResult
        """
        slug = project_name.lower().replace(" ", "-").replace("_", "-")
        parent = Path(base_dir).resolve() if base_dir else WORKSPACE_DIR
        project_path = parent / slug

        # Safety: ensure inside workspace
        try:
            project_path.relative_to(WORKSPACE_DIR)
        except ValueError:
            return ScaffoldResult(
                project_name=project_name,
                project_path=str(project_path),
                template=template,
                files_created=[],
                success=False,
                error="Project path is outside workspace",
            )

        if template not in _TEMPLATES:
            return ScaffoldResult(
                project_name=project_name,
                project_path=str(project_path),
                template=template,
                files_created=[],
                success=False,
                error=f"Unknown template '{template}'. Available: {list(_TEMPLATES.keys())}",
            )

        project_path.mkdir(parents=True, exist_ok=True)
        files_created: list[str] = []

        tmpl = _TEMPLATES[template]
        vars_map = {"project_name": project_name, "project_slug": slug}

        for rel_path_tmpl, content_tmpl in tmpl.items():
            # Resolve template variables in path and content
            rel_path = rel_path_tmpl.format(**vars_map)
            content  = content_tmpl.format(**vars_map)

            file_path = project_path / rel_path
            file_path.parent.mkdir(parents=True, exist_ok=True)

            if not file_path.exists():
                file_path.write_text(content, encoding="utf-8")
                files_created.append(rel_path)

        log.info("Scaffolded %r (%s) at %s", project_name, template, project_path)
        return ScaffoldResult(
            project_name=project_name,
            project_path=str(project_path),
            template=template,
            files_created=files_created,
            success=True,
        )

    # ── Detection ──────────────────────────────────────────────────────────────

    def detect_project(self, project_path: str) -> ProjectMeta:
        """Detect project type, entry point, and build run command."""
        path = Path(project_path).resolve()

        if not path.is_dir():
            return ProjectMeta(
                path=str(path), name=path.name, type="unknown",
                template=None, entry_point=None, has_deps=False,
                run_command="",
            )

        # Python detection
        has_requirements = (path / "requirements.txt").exists()
        has_setup        = (path / "setup.py").exists() or (path / "pyproject.toml").exists()
        has_uvicorn_dep  = has_requirements and "uvicorn" in (path / "requirements.txt").read_text(encoding="utf-8")

        for entry in ["main.py", "app.py", "server.py", "run.py", "cli.py", "__main__.py"]:
            if (path / entry).exists():
                if has_uvicorn_dep:
                    run_cmd = f"uvicorn {entry.replace('.py', '')}:app --host 0.0.0.0 --port 8000"
                else:
                    run_cmd = f"python {entry}"
                return ProjectMeta(
                    path=str(path), name=path.name, type="python",
                    template="fastapi" if has_uvicorn_dep else "script",
                    entry_point=entry, has_deps=has_requirements or has_setup,
                    run_command=run_cmd,
                )

        # Node.js detection
        pkg = path / "package.json"
        if pkg.exists():
            try:
                data = json.loads(pkg.read_text(encoding="utf-8"))
                scripts = data.get("scripts", {})
                run_cmd = "npm start" if "start" in scripts else "node index.js"
            except Exception:
                run_cmd = "node index.js"
            return ProjectMeta(
                path=str(path), name=path.name, type="node",
                template="node-api", entry_point="index.js",
                has_deps=(path / "node_modules").exists(),
                run_command=run_cmd,
            )

        return ProjectMeta(
            path=str(path), name=path.name, type="unknown",
            template=None, entry_point=None, has_deps=False,
            run_command="",
        )

    # ── Dependency installation ────────────────────────────────────────────────

    def install_deps(self, project_path: str) -> RunResult:
        """
        Install project dependencies safely.

        Python: pip install -r requirements.txt (with --no-deps to avoid supply-chain risk)
        Node:   npm install
        """
        meta = self.detect_project(project_path)
        path = Path(project_path).resolve()
        t0   = time.monotonic()

        if meta.type == "python":
            req_file = path / "requirements.txt"
            if not req_file.exists():
                return RunResult(
                    project_path=project_path, command="pip install",
                    exit_code=0, stdout="No requirements.txt — nothing to install.",
                    stderr="", duration_s=0.0, success=True,
                )
            return self._run_process(
                ["pip", "install", "-r", "requirements.txt"],
                cwd=str(path),
                label="pip install",
            )

        if meta.type == "node":
            return self._run_process(
                ["npm", "install", "--prefer-offline"],
                cwd=str(path),
                label="npm install",
            )

        return RunResult(
            project_path=project_path, command="install_deps",
            exit_code=1, stdout="",
            stderr="Unknown project type — cannot install deps.",
            duration_s=0.0, success=False,
        )

    # ── Project run ───────────────────────────────────────────────────────────

    def run_project(
        self,
        project_path: str,
        timeout: float = 30.0,
        command_override: str | None = None,
    ) -> RunResult:
        """
        Run the project and capture output.

        Args:
            project_path:     Absolute path to the project.
            timeout:          Max seconds before SIGTERM.
            command_override: Override auto-detected run command.

        Returns:
            RunResult with stdout/stderr/errors.
        """
        meta = self.detect_project(project_path)

        if not meta.run_command and not command_override:
            return RunResult(
                project_path=project_path, command="",
                exit_code=1, stdout="",
                stderr="Could not detect run command for this project.",
                duration_s=0.0, success=False,
            )

        cmd_str = command_override or meta.run_command
        cmd_list = cmd_str.split()

        return self._run_process(cmd_list, cwd=project_path, label=cmd_str, timeout=timeout)

    # ── File management ────────────────────────────────────────────────────────

    def write_project_file(
        self,
        project_path: str,
        relative_path: str,
        content: str,
    ) -> bool:
        """Write a file inside the project (workspace-scoped)."""
        fs = get_fs()
        full_path = str(Path(project_path) / relative_path)
        # Normalize to workspace-relative
        try:
            rel = Path(full_path).resolve().relative_to(WORKSPACE_DIR)
        except ValueError:
            log.warning("write_project_file: path outside workspace: %s", full_path)
            return False
        result = fs.write_file(str(rel), content)
        return result.success

    def read_project_file(self, project_path: str, relative_path: str) -> str | None:
        """Read a file from the project. Returns None on error."""
        fs = get_fs()
        full_path = str(Path(project_path) / relative_path)
        try:
            rel = Path(full_path).resolve().relative_to(WORKSPACE_DIR)
        except ValueError:
            return None
        result = fs.read_file(str(rel))
        return result.data if result.success else None

    def list_project_files(self, project_path: str) -> list[str]:
        """Return all files in the project (relative paths)."""
        path = Path(project_path).resolve()
        if not path.is_dir():
            return []
        files = []
        for f in path.rglob("*"):
            if f.is_file() and "__pycache__" not in str(f) and ".git" not in str(f):
                try:
                    files.append(str(f.relative_to(path)))
                except ValueError:
                    pass
        return sorted(files)

    # ── Private ────────────────────────────────────────────────────────────────

    @staticmethod
    def _run_process(
        cmd: list[str],
        cwd: str,
        label: str,
        timeout: float = 30.0,
    ) -> RunResult:
        import subprocess
        import re

        t0 = time.monotonic()
        try:
            proc = subprocess.run(
                cmd,
                capture_output=True,
                text=True,
                cwd=cwd,
                timeout=timeout,
            )
            stdout  = proc.stdout[:8192]
            stderr  = proc.stderr[:4096]
            success = proc.returncode == 0
        except subprocess.TimeoutExpired:
            return RunResult(
                project_path=cwd, command=label,
                exit_code=None, stdout="", stderr="Timed out.",
                duration_s=time.monotonic() - t0, success=False,
                errors=["timeout"],
            )
        except Exception as exc:
            return RunResult(
                project_path=cwd, command=label,
                exit_code=1, stdout="", stderr=str(exc),
                duration_s=time.monotonic() - t0, success=False,
                errors=["exception"],
            )

        # Detect error patterns in output
        error_patterns = [
            (re.compile(r"SyntaxError|IndentationError", re.I), "syntax_error"),
            (re.compile(r"ModuleNotFoundError|ImportError",  re.I), "import_error"),
            (re.compile(r"Traceback \(most recent call last\)", re.I), "traceback"),
            (re.compile(r"TypeError|ValueError|KeyError",    re.I), "runtime_error"),
            (re.compile(r"npm ERR!|ENOENT",                  re.I), "npm_error"),
        ]
        errors: list[str] = []
        combined = stdout + stderr
        for pat, label_err in error_patterns:
            if pat.search(combined):
                errors.append(label_err)

        return RunResult(
            project_path=cwd, command=label,
            exit_code=proc.returncode, stdout=stdout, stderr=stderr,
            duration_s=time.monotonic() - t0,
            success=success and not errors,
            errors=errors,
        )


# ── Singleton ──────────────────────────────────────────────────────────────────

_wm: WorkspaceManager | None = None


def get_workspace_manager() -> WorkspaceManager:
    """Return the global WorkspaceManager singleton."""
    global _wm
    if _wm is None:
        _wm = WorkspaceManager()
    return _wm
