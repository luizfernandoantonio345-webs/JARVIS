"""
WorkspaceManager — full project lifecycle automation.

Handles:
  - Project scaffolding from templates (FastAPI, CLI, library, React)
  - Dependency installation (pip, npm)
  - Project detection and metadata
  - Run lifecycle: start → watch → stop
  - Build artifacts management

All operations are:
  - Scoped to WORKSPACE_DIR
  - Logged with full audit trail
  - Non-destructive by default (backup before overwrite)

Templates bundled:
  - fastapi   → FastAPI REST API with uvicorn
  - cli       → Click CLI tool
  - library   → Python package with setup.py
  - script    → Single-file Python script
  - node-api  → Express.js REST API
  - react     → Vite + React frontend

Usage:
    from services.workspace_manager import get_workspace_manager
    wm = get_workspace_manager()
    path = wm.scaffold("my-api", template="fastapi")
    result = wm.install_deps(path)
    result = wm.run_project(path)
"""

